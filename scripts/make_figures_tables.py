def box(ax, x, y, w, h, text, fc="#f4f3f0", ec=INK2, bold=False, fs=6.3):
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.008,rounding_size=0.012", fc=fc, ec=ec, lw=0.7))
    ax.text(x + w/2, y + h/2, text, ha="center", va="center", fontsize=fs, weight="bold" if bold else "normal", wrap=True)
def arrow(ax, x1, y1, x2, y2, txt=None, dashed=False):
    ax.annotate("", (x2, y2), (x1, y1), arrowprops=dict(arrowstyle="-|>", lw=0.7, color=INK2, ls="--" if dashed else "-", mutation_scale=7))
    if txt: ax.text((x1+x2)/2, (y1+y2)/2 + 0.012, txt, fontsize=5.6, color=INK2, ha="center", va="bottom")

