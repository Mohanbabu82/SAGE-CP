def tex_table(df, name, caption, label, colfmt=None):
    colfmt = colfmt or ("l" + "r" * (df.shape[1] - 1))
    body = df.to_latex(index=False, escape=True, column_format=colfmt, na_rep="--")
    with open(f"{OUT}/tables/{name}.tex", "w") as f:
        f.write("% Generated by make_figures_tables.py from the SAGE-CP v2.1 results files\n")
        f.write("\\begin{table}[!t]\n\\caption{" + caption + "}\n\\label{" + label + "}\n\\centering\n\\footnotesize\n")
        f.write(body)
        f.write("\\end{table}\n")
    df.to_csv(f"{OUT}/tables/{name}.csv", index=False)

