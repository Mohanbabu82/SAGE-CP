#!/usr/bin/env python3
"""Reproduce every table and figure of the SAGE-CP v2.1 IEEE Access manuscript.

Usage:  python make_figures_tables.py <results_dir> <out_dir>

Reads only the archived CSV outputs of the executed SAGE-CP v2.1 run.
No value is typed in by hand; every number comes from a results file.
Error bars are drawn only where the run computed fixed-region bootstrap
intervals (table1_methods_target_long.csv, table_region_inference.csv).
No significance markers are drawn.
"""
